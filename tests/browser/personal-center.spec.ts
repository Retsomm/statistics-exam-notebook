import {test,expect} from '@playwright/test';
import {readFileSync} from 'node:fs';
import {emptyState} from '../../lib/study.mjs';
import {createMockRun,finishMockPaper} from '../../lib/mock-exam.mjs';
import {openPersonalSection} from './personal-navigation';
const bank=JSON.parse(readFileSync('data/bank.json','utf8'));
const now=Date.parse('2026-11-17T04:00:00Z');
for(const width of [360,390,1440])test(`personal center combines activity, collections and backups at ${width}px`,async({page})=>{
 await page.setViewportSize({width,height:1000});await page.clock.install({time:new Date(now)});
 const q=bank.questions[0],state=emptyState(),run=createMockRun(bank,[],'11111111-1111-4111-8111-111111111111',now-3600000);
 const mockQuestion=bank.questions.find((q:any)=>q.id===run.papers[0].ids[0]);
 run.papers[0]=finishMockPaper({...run.papers[0],startedAt:new Date(now-600000).toISOString(),choices:{[mockQuestion.id]:mockQuestion.accepted[0].split('')}},new Map(bank.questions.map((q:any)=>[q.id,q])),now);
 state.mockRuns=[run];state.visitDays=['2026-11-15','2026-11-16'];state.bookmarks=[q.id];
 state.history=[{id:q.id,answer:'A',correct:true,time:new Date(now-3600000).toISOString()},{id:q.id,answer:'B',correct:false,time:new Date(now-1800000).toISOString()},{id:q.id,answer:'A',correct:true,time:'2026-11-16T00:00:00Z'}];
 await page.addInitScript(state=>{if(!localStorage.getItem('yueri:next:v1:guest'))localStorage.setItem('yueri:next:v1:guest',JSON.stringify(state));},state);
 await page.goto('/demo/');await openPersonalSection(page,'學習看板');
 await expect(page.getByRole('navigation',{name:'主要導覽'}).getByRole('button')).toHaveCount(4);
 await expect(page.getByRole('tablist',{name:'個人中心功能'}).getByRole('tab')).toHaveCount(4);
 await expect(page.locator('.personal-stat').filter({hasText:'連續造訪'}).locator('strong')).toHaveText('3天');
 await expect(page.locator('.personal-stat').filter({hasText:'今日作答'}).locator('strong')).toHaveText('3次');
 await expect(page.locator('.personal-stat').filter({hasText:'近 7 天正確率'}).locator('strong')).toHaveText('75%');
 await page.getByRole('button',{name:'2026-11-16，已記錄造訪，作答 1 次',exact:true}).click();
 await expect(page.getByRole('heading',{name:'11 月 16 日的學習紀錄',exact:true})).toBeVisible();
 await expect(page.getByRole('region',{name:'當日學習紀錄'})).toContainText('日常練習 1 次');
 await page.getByRole('button',{name:'回到今天',exact:true}).click();
 await expect(page.getByRole('region',{name:'當日學習紀錄'})).toContainText('模擬考作答 1 次');
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
 await page.getByRole('button',{name:/我的收藏/}).click();await expect(page.locator('.question-row')).toHaveCount(1);
 await page.getByRole('tab',{name:'重點整理',exact:true}).click();await expect(page.getByRole('group',{name:'重點整理科目'})).toBeVisible();
 await page.getByRole('tab',{name:'備份與資料',exact:true}).click();
 await page.getByLabel('匯入統計備份').setInputFiles({name:'study-backup.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify({...emptyState(),visitDays:['2026-11-14']}))});
 await expect.poll(()=>page.evaluate(()=>JSON.parse(localStorage.getItem('yueri:next:v1:guest')||'{}').visitDays)).toEqual(['2026-11-14','2026-11-15','2026-11-16','2026-11-17']);
 const downloadPromise=page.waitForEvent('download');await page.getByRole('button',{name:'匯出備份',exact:true}).click();
 const downloaded=await downloadPromise,stream=await downloaded.createReadStream(),chunks:Buffer[]=[];
 for await(const chunk of stream!)chunks.push(Buffer.from(chunk));
 const exported=JSON.parse(Buffer.concat(chunks).toString());expect(exported.bookmarks).toContain(q.id);expect(exported.visitDays).toHaveLength(4);
 await page.reload();await openPersonalSection(page,'學習看板');
 await expect(page.locator('.personal-stat').filter({hasText:'連續造訪'}).locator('strong')).toHaveText('4天');
 await expect(page.locator('.personal-trend-bars button')).toHaveCount(14);
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
});
test('visible midnight and reload record each Taiwan visit day once without backfilling',async({page})=>{
 await page.clock.install({time:new Date('2026-11-17T15:59:10Z')});await page.goto('/demo/');await openPersonalSection(page,'學習看板');
 const visits=()=>page.evaluate(()=>JSON.parse(localStorage.getItem('yueri:next:v1:guest')||'{}').visitDays);
 await expect.poll(visits).toEqual(['2026-11-17']);
 await page.clock.fastForward(61000);await expect.poll(visits).toEqual(['2026-11-17','2026-11-18']);
 await page.reload();await openPersonalSection(page,'學習看板');await expect.poll(visits).toEqual(['2026-11-17','2026-11-18']);
 await expect(page.locator('.personal-stat').filter({hasText:'連續造訪'}).locator('strong')).toHaveText('2天');
 await page.getByRole('tab',{name:'學習看板',exact:true}).press('End');await expect(page.getByRole('tab',{name:'備份與資料',exact:true})).toBeFocused();
 await page.keyboard.press('Home');await expect(page.getByRole('tab',{name:'學習看板',exact:true})).toBeFocused();
});
